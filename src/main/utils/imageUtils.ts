export const convertImageToBmp = (
  inputPath: string,
  outputPath: string,
): Promise<void> => {
  return new Promise((resolve, reject) => {
    ffmpeg(inputPath)
      .output(outputPath)
      .outputOptions(["-pix_fmt", "bgr24"]) // Standard BMP pixel format
      .on("end", () => resolve())
      .on("error", (err) =>
        reject(new Error(`Failed to convert image: ${err.message}`)),
      )
      .run();
  });
};
